package airimportgate

import (
	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/promauto"
)

var (
	// ImportLeaseTotal 导入租约创建/终态计数。
	ImportLeaseTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "aa_airimportgate_import_lease_total",
		Help: "Import lease transitions by state (open/importing/imported/aborted/expired)",
	}, []string{"state"})
	// BlobReplayTotal 密封 blob 重放拒绝计数。
	BlobReplayTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "aa_airimportgate_blob_replay_total",
		Help: "Sealed blob replay rejection events",
	}, []string{"session_id"})
	// PhaseConflictTotal 相位冲突证明生成计数。
	PhaseConflictTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "aa_airimportgate_phase_conflict_total",
		Help: "Phase conflict proofs generated by conflict kind",
	}, []string{"kind"})
	// QuorumDriftTotal 法定人数漂移拒绝计数。
	QuorumDriftTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "aa_airimportgate_quorum_drift_total",
		Help: "Quorum drift rejections (actual < threshold)",
	}, []string{"session_id"})
	// ImportDurationSeconds 导入操作耗时分布。
	ImportDurationSeconds = promauto.NewHistogramVec(prometheus.HistogramOpts{
		Name: "aa_airimportgate_import_duration_seconds",
		Help: "ImportSealed end-to-end duration in seconds",
		Buckets: []float64{0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1},
	}, []string{"result"})
	// WorkerExpiryCycles 过期吊销 Worker 执行轮次。
	WorkerExpiryCycles = promauto.NewCounter(prometheus.CounterOpts{
		Name: "aa_airimportgate_worker_expiry_cycles_total",
		Help: "Lease expiry worker execution cycles",
	})
	// WorkerExpiredLeases 过期吊销 Worker 处理的租约数。
	WorkerExpiredLeases = promauto.NewCounter(prometheus.CounterOpts{
		Name: "aa_airimportgate_worker_expired_leases_total",
		Help: "Leases expired by the expiry worker",
	})
	// WorkerReplayScanCycles 重放扫描 Worker 轮次。
	WorkerReplayScanCycles = promauto.NewCounter(prometheus.CounterOpts{
		Name: "aa_airimportgate_worker_replay_scan_cycles_total",
		Help: "Replay scan worker execution cycles",
	})
	// WorkerConflictEscalations 冲突升级 Worker 处理的冲突证明数。
	WorkerConflictEscalations = promauto.NewCounter(prometheus.CounterOpts{
		Name: "aa_airimportgate_worker_conflict_escalations_total",
		Help: "Conflict proofs escalated to proven by the escalation worker",
	})
)
