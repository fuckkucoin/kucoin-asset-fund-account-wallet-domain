func liveSnapshot(c *gin.Context, rt *app.Runtime) slo.Snapshot {
	_, code := rt.Ready(c.Request.Context())
	lag := rt.Market.Lag()
	down := 0
	if rt.Wallet != nil {
		down = rt.Wallet.Registry().Health().DownCount()
	}
	return slo.Live(slo.ProcessView{
		ReadyOK:            code == 200,
		NodesDown:          down,
		MarketLagMs:        lag.LastLagMs,
		MarketStaleRate:    lag.StaleRate,
		MarketApplied:      lag.Applied,
		MarketStaleDropped: lag.StaleDropped,
	}, slo.GatherPrometheus())
}
