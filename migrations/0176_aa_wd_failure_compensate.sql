;

-- 作者：Kinsley
CREATE TABLE IF NOT EXISTS wd_failures (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  idempotency_key VARCHAR(191) NOT NULL,
  fingerprint VARCHAR(512) NOT NULL DEFAULT '',
  transfer_id VARCHAR(64) NOT NULL,
  user_id VARCHAR(64) NOT NULL,
  asset VARCHAR(32) NOT NULL,
  chain VARCHAR(32) NOT NULL DEFAULT '',
  source VARCHAR(32) NOT NULL,
  code VARCHAR(64) NOT NULL,
  reason_code VARCHAR(64) NOT NULL DEFAULT '',
  reason VARCHAR(255) NOT NULL DEFAULT '',
  user_text VARCHAR(255) NOT NULL DEFAULT '',
  tx_hash VARCHAR(128) NOT NULL DEFAULT '',
  live_hash INT NOT NULL DEFAULT 0,
  chain_blocked INT NOT NULL DEFAULT 0,
  broadcast_status VARCHAR(32) NOT NULL DEFAULT '',
  freeze_state VARCHAR(32) NOT NULL DEFAULT '',
  chain_state VARCHAR(32) NOT NULL DEFAULT '',
  shard_plan_id VARCHAR(64) NOT NULL DEFAULT '',
  shard_id VARCHAR(64) NOT NULL DEFAULT '',
  shard_seq INT NOT NULL DEFAULT 0,
  amount VARCHAR(64) NOT NULL DEFAULT '0',
  filled_amount VARCHAR(64) NOT NULL DEFAULT '0',
  failed_amount VARCHAR(64) NOT NULL DEFAULT '0',
  in_flight_amount VARCHAR(64) NOT NULL DEFAULT '0',
  fee_reserved VARCHAR(64) NOT NULL DEFAULT '0',
  occupancy VARCHAR(64) NOT NULL DEFAULT '0',
  protected_amount VARCHAR(64) NOT NULL DEFAULT '0',
  compensable VARCHAR(64) NOT NULL DEFAULT '0',
  available_snapshot VARCHAR(64) NOT NULL DEFAULT '',
  frozen_snapshot VARCHAR(64) NOT NULL DEFAULT '',
  fee_snapshot VARCHAR(64) NOT NULL DEFAULT '',
  status VARCHAR(32) NOT NULL,
  plan_id VARCHAR(64) NOT NULL DEFAULT '',
  may_auto INT NOT NULL DEFAULT 0,
  occurred_at DATETIME(3) NOT NULL,
  ingested_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  UNIQUE KEY uk_wd_failures_idem (idempotency_key),
  KEY idx_wd_failures_transfer (transfer_id),
  KEY idx_wd_failures_user_asset (user_id, asset)
);

CREATE TABLE IF NOT EXISTS compensate_plans (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  failure_id VARCHAR(64) NOT NULL,
  transfer_id VARCHAR(64) NOT NULL,
  user_id VARCHAR(64) NOT NULL,
  asset VARCHAR(32) NOT NULL,
  state VARCHAR(32) NOT NULL,
  auto_ok INT NOT NULL DEFAULT 0,
  force_human INT NOT NULL DEFAULT 0,
  live_hash INT NOT NULL DEFAULT 0,
  chain_blocked INT NOT NULL DEFAULT 0,
  policy_code VARCHAR(64) NOT NULL DEFAULT '',
  policy_version INT NOT NULL DEFAULT 1,
  idempotency_key VARCHAR(191) NOT NULL DEFAULT '',
  human_ticket_id VARCHAR(64) NOT NULL DEFAULT '',
  human_actor VARCHAR(64) NOT NULL DEFAULT '',
  human_approver VARCHAR(64) NOT NULL DEFAULT '',
  human_reason VARCHAR(255) NOT NULL DEFAULT '',
  abort_reason VARCHAR(255) NOT NULL DEFAULT '',
  timeout_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  committed_at DATETIME(3) NULL,
  UNIQUE KEY uk_compensate_plans_failure (failure_id),
  KEY idx_compensate_plans_state (state),
  KEY idx_compensate_plans_transfer (transfer_id)
);

CREATE TABLE IF NOT EXISTS compensate_legs (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  plan_id VARCHAR(64) NOT NULL,
  seq INT NOT NULL,
  kind VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL,
  amount VARCHAR(64) NOT NULL DEFAULT '0',
  asset VARCHAR(32) NOT NULL DEFAULT '',
  user_id VARCHAR(64) NOT NULL DEFAULT '',
  transfer_id VARCHAR(64) NOT NULL DEFAULT '',
  idempotency_key VARCHAR(191) NOT NULL,
  result_ref VARCHAR(64) NOT NULL DEFAULT '',
  reason_code VARCHAR(64) NOT NULL DEFAULT '',
  err_text VARCHAR(255) NOT NULL DEFAULT '',
  attempts INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  UNIQUE KEY uk_compensate_legs_idem (idempotency_key),
  UNIQUE KEY uk_compensate_legs_seq (plan_id, seq)
);

CREATE TABLE IF NOT EXISTS rollback_entries (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  plan_id VARCHAR(64) NOT NULL DEFAULT '',
  leg_id VARCHAR(64) NOT NULL DEFAULT '',
  failure_id VARCHAR(64) NOT NULL DEFAULT '',
  transfer_id VARCHAR(64) NOT NULL DEFAULT '',
  user_id VARCHAR(64) NOT NULL,
  asset VARCHAR(32) NOT NULL,
  kind VARCHAR(64) NOT NULL,
  amount VARCHAR(64) NOT NULL DEFAULT '0',
  available_before VARCHAR(64) NOT NULL DEFAULT '0',
  available_after VARCHAR(64) NOT NULL DEFAULT '0',
  frozen_before VARCHAR(64) NOT NULL DEFAULT '0',
  frozen_after VARCHAR(64) NOT NULL DEFAULT '0',
  fee_before VARCHAR(64) NOT NULL DEFAULT '0',
  fee_after VARCHAR(64) NOT NULL DEFAULT '0',
  idempotency_key VARCHAR(191) NOT NULL,
  fingerprint VARCHAR(512) NOT NULL DEFAULT '',
  reason_code VARCHAR(64) NOT NULL DEFAULT '',
  path VARCHAR(64) NOT NULL DEFAULT '',
  applied INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL,
  UNIQUE KEY uk_rollback_entries_idem (idempotency_key),
  KEY idx_rollback_entries_user (user_id, asset),
  KEY idx_rollback_entries_transfer (transfer_id)
);

CREATE TABLE IF NOT EXISTS auto_policies (
  code VARCHAR(64) NOT NULL PRIMARY KEY,
  version INT NOT NULL DEFAULT 1,
  auto_allowed INT NOT NULL DEFAULT 0,
  force_human INT NOT NULL DEFAULT 0,
  dual_confirm INT NOT NULL DEFAULT 0,
  timeout_sec INT NOT NULL DEFAULT 900,
  leg_template VARCHAR(255) NOT NULL DEFAULT '',
  note VARCHAR(255) NOT NULL DEFAULT '',
  updated_by VARCHAR(64) NOT NULL DEFAULT '',
  updated_at DATETIME(3) NOT NULL
);
